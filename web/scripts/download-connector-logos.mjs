#!/usr/bin/env node
// Downloads each connector's official logo from Brandfetch's public logo CDN
// once and saves it under web/public/connector-logos/, plus a manifest both
// the static files and web/app/components/ConnectorLogo.tsx read from. The
// running app never calls Brandfetch itself — this script is the only thing
// that does, and only when you re-run it (e.g. after adding a new connector).
//
// Uses the free, unauthenticated cdn.brandfetch.io/<domain>?c=<clientId>
// logo-link endpoint (see https://brandfetch.com/developers/logo-link) —
// NOT the paid Brand API, which has a strict per-plan request quota.
//
// Usage: node --env-file=.env.local scripts/download-connector-logos.mjs
// (run from web/; BRANDFETCH_CLIENT_ID is optional — falls back to the
// public client id already used elsewhere in this app)

