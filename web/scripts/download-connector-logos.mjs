// Public (non-secret) Brandfetch client id — already embedded client-side
// elsewhere in this app (see git history of web/app/page.tsx's old
// heroConnectors logoUrl entries), safe to default here.
const DEFAULT_CLIENT_ID = "1bxec69tls8qaj83i3hc2bbf373tgfgTpns";

const EXT_BY_CONTENT_TYPE = {
  "image/svg+xml": "svg",
  "image/png": "png",
  "image/webp": "webp",
  "image/jpeg": "jpg",
};

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const OUT_DIR = path.join(__dirname, "..", "public", "connector-logos");
const MANIFEST_TS_PATH = path.join(__dirname, "..", "lib", "connector-logo-manifest.ts");

function sleep(ms) {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

async function fetchWithRetry(url, { retries = 3, baseDelayMs = 1000 } = {}) {
  for (let attempt = 0; ; attempt += 1) {
    const response = await fetch(url);
    if (response.ok || attempt >= retries) return response;
    const delay = baseDelayMs * 2 ** attempt;
    console.warn(`  ...${response.status}, retrying in ${Math.round(delay / 1000)}s (attempt ${attempt + 1}/${retries})`);
    await sleep(delay);
  }
}

async function downloadOne(provider, domain, clientId) {
  const response = await fetchWithRetry(
    `https://cdn.brandfetch.io/${encodeURIComponent(domain)}?c=${encodeURIComponent(clientId)}`,
  );
  if (!response.ok) throw new Error(`brandfetch cdn ${response.status} for ${domain}`);

  const contentType = response.headers.get("content-type")?.split(";")[0]?.trim();
  const ext = EXT_BY_CONTENT_TYPE[contentType] ?? "png";
  const buffer = Buffer.from(await response.arrayBuffer());
  if (buffer.length === 0) throw new Error(`empty response for ${domain}`);

  const filename = `${provider}.${ext}`;
  await writeFile(path.join(OUT_DIR, filename), buffer);
  return filename;
}

async function main() {
  const clientId = process.env.BRANDFETCH_CLIENT_ID || DEFAULT_CLIENT_ID;

  await mkdir(OUT_DIR, { recursive: true });

  const manifest = {};
  const failures = [];
  const entries = Object.entries(CONNECTOR_DOMAINS);

  for (const [provider, domain] of entries) {
    try {
      const filename = await downloadOne(provider, domain, clientId);
      manifest[provider] = filename;
      console.log(`✓ ${provider.padEnd(16)} -> connector-logos/${filename}`);
    } catch (error) {
      failures.push(provider);
      console.warn(`✗ ${provider.padEnd(16)} skipped: ${error instanceof Error ? error.message : error}`);
    }
    await sleep(150);
  }

  await writeFile(
    path.join(OUT_DIR, "manifest.json"),
    JSON.stringify(manifest, null, 2) + "\n",
  );

  const tsSource =
    `// AUTO-GENERATED by web/scripts/download-connector-logos.mjs — do not edit by hand.\n` +
    `// Maps provider id -> filename under /public/connector-logos/, for connectors\n` +
    `// whose official logo was successfully downloaded. Missing entries fall back\n` +
    `// to the hand-drawn ConnectorIcons component (see ConnectorLogo.tsx).\n` +
    `export const CONNECTOR_LOGO_MANIFEST: Record<string, string> = ${JSON.stringify(manifest, null, 2)};\n`;
  await writeFile(MANIFEST_TS_PATH, tsSource);

  console.log(`\nDownloaded ${entries.length - failures.length}/${entries.length} logos.`);
  if (failures.length > 0) {
    console.log(`Skipped (will use fallback icon): ${failures.join(", ")}`);
  }
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
